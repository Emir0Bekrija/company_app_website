export function translate(locale: DemoLocale, key: string, params?: Record<string, string | number>) {
  const entry = STRINGS[key]
  if (!entry) return key
  const text = entry[locale === 'bs' ? 1 : 0]
  return params ? text.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? '')) : text
}
