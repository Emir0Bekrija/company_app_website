/**
 * Copies the app's theme layer into vendor/app so the marketing site shows the real
 * themes without changing the app. Reads from the app, writes only inside this repo.
 *
 *   node scripts/sync-app.mjs           copy
 *   node scripts/sync-app.mjs --check   exit 1 if vendor/app has drifted from the app
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const app = resolve(process.env.NAVITECS_APP_DIR ?? join(root, '..', 'company-system', 'CompanyApp.API_WEB'))
const check = process.argv.includes('--check')

const rewriteImports = (src) => src
  .replaceAll("'@/app/theme/", "'@/vendor/app/theme/")
  .replaceAll("'@/components/ui/star-shape'", "'@/vendor/app/ui/star-shape'")

/** Keeps the token layer, keyframes, Nebula frosting and motion rules; drops page-level CSS. */
function tokensCss(src) {
  const start = src.indexOf('/* Themes are chosen by the user')
  const baseStart = src.indexOf('@layer base {')
  const nebula = src.indexOf('/* Nebula draws a starfield')
  if (start < 0 || baseStart < 0 || nebula < 0) throw new Error('index.css layout changed; update tokensCss()')
  const head = src.slice(start, baseStart)
    .replace(/--font-sans:[^;]+;/, '--font-sans: var(--font-inter), sans-serif;')
    .replace(/^\s*color-scheme: dark;\n/m, '')
  return `/* Generated by scripts/sync-app.mjs from the app's src/index.css. Do not edit. */\n${head}@layer base {\n  ${src.slice(nebula)}`
}

const files = [
  ...['theme-config', 'theme-palette', 'theme-presets', 'accent-shades', 'tint', 'apply-theme']
    .map((n) => [`src/app/theme/${n}.ts`, `vendor/app/theme/${n}.ts`, rewriteImports]),
  ['src/components/ui/star-shape.ts', 'vendor/app/ui/star-shape.ts', rewriteImports],
  ['src/components/ui/nebula-scene.tsx', 'vendor/app/ui/nebula-scene.tsx', rewriteImports],
  ['src/app/features/user-settings/components/theme-preview.tsx', 'vendor/app/ui/theme-preview.tsx', rewriteImports],
  ['src/index.css', 'vendor/app/tokens.css', tokensCss],
]

let drift = 0
for (const [from, to, transform] of files) {
  const source = join(app, from)
  if (!existsSync(source)) {
    if (check) { console.warn(`skip: app not found at ${source}`); continue }
    throw new Error(`Missing ${source}`)
  }
  const next = transform(readFileSync(source, 'utf8').replaceAll('\r\n', '\n'))
  const target = join(root, to)
  if (check) {
    const same = existsSync(target) && readFileSync(target, 'utf8') === next
    if (!same) { drift++; console.error(`drift: ${to}`) }
    continue
  }
  mkdirSync(dirname(target), { recursive: true })
  writeFileSync(target, next)
  console.log(`synced ${to}`)
}

if (check) {
  console.log(drift ? `${drift} file(s) drifted. Run npm run sync:app.` : 'vendor/app matches the app.')
  process.exit(drift ? 1 : 0)
}
